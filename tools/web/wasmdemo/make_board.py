"""Regenerate the demo's board model (`board.lp` + `board.json`) from the account.

The browser demo's SOLVER half needs one board instance: the pool-best team's LEADER
board as an integer program. This extracts it the same way the feasibility study did
(tree_optimise node graph + prices + per-node values, sockets valued by socket_optimise),
writes it as a standard CPLEX LP for highs.wasm, plus a small JSON of node metadata for
the page to map the solution back to node ids.

Account-derived, so the outputs are gitignored and regenerated by `setup.py`. Run from
the repo root. Needs the proxyenv interpreter (tree_optimise's deps) + `highspy`
(`pip install highspy`, MIT) for the LP export.

    tools/recon/proxy/proxyenv/Scripts/python.exe tools/web/wasmdemo/make_board.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
PROXY = REPO / "tools" / "recon" / "proxy"
sys.path.insert(0, str(PROXY))

import tree_optimise as T  # noqa: E402
import socket_optimise as SO  # noqa: E402


def build_instance():
    """The pool-best team's leader board: nodes, point costs, adjacency, per-node
    values (RED on the leader, GREEN/YELLOW global, BLUE 0), and the respec budget."""
    prices = T._prices()
    owned = T._owned_nodes()
    balance, _ = T.balance_from_disk()
    oracle = T.Oracle(pool_size=6, song=None, charts_path=None, scenario="account")
    oracle.prime()
    leader_id, member_ids = oracle._teams[0]
    graphs = T._graphs(oracle.skilltree)
    values = T._branch_values(oracle, graphs, prices, leader_id, member_ids)
    _bal, points, _start, _levels = T.respec_budget(owned, prices, balance)

    leader_chr = "chr-" + leader_id.split("-")[1]
    g = graphs[leader_chr]
    budget = int(points[leader_chr])

    def leader_value(n: str) -> float:
        if n.startswith("B"):  # blue = member-scoped, worthless on the leader board
            return 0.0
        return float(values.get(n, 0.0))

    nodes = sorted(g.keys())
    inst = {
        "leader_id": leader_id,
        "member_ids": list(member_ids),
        "leader_chr": leader_chr,
        "root": T.ROOT,
        "budget": budget,
        "nodes": nodes,
        "cost": {n: int(prices.get(n, {}).get("points", 0)) for n in nodes},
        "value": {n: leader_value(n) for n in nodes},
        "edges": sorted({tuple(sorted((a, b))) for a in g for b in g[a]}),
    }
    return inst, oracle, leader_id, member_ids


def add_socket_values(inst, leader_id, member_ids):
    """Value the leader's Connect sockets (best card, on the valued board) and fold
    them onto the socket nodes' objective value -- exactly as the feasibility study did."""
    lc = inst["leader_chr"]
    root = inst["root"]
    # a board context that carries the valuable red, so the socket buff is real
    valued = [root] + [n for n in inst["nodes"] if inst["value"][n] > 0 and not n.startswith("S")]
    state = {lc: {"nodes": valued, "slots": {}}}
    tmp = HERE / "_socket_ctx.json"
    tmp.write_text(json.dumps(state), encoding="utf-8")
    try:
        res = SO.optimise(pool=6, board_state_path=tmp, scenario="account",
                          leader_id=leader_id, member_ids=tuple(member_ids))
        for p in res["placements"]:
            if p["chr"] == lc and p["socket"] in inst["value"]:
                inst["value"][p["socket"]] = float(p["isolated_value"])
    finally:
        tmp.unlink(missing_ok=True)


def write_lp(inst, out_lp: Path):
    """Export the connected-subgraph knapsack (single-commodity-flow connectivity) as a
    standard CPLEX LP for highs.wasm -- by hand, so the build needs no solver library.

    Variables are named after the node ids (`x_<node>`), so the page maps the solution
    back by name; LP names can't contain '-', so it becomes '_'."""
    nodes, cost, val = inst["nodes"], inst["cost"], inst["value"]
    root, B = inst["root"], inst["budget"]
    edges = [tuple(e) for e in inst["edges"]]
    N = len(nodes)
    xn = lambda n: "x_" + n.replace("-", "_")
    fn = lambda a, b: "f_" + a.replace("-", "_") + "__" + b.replace("-", "_")

    def expr(coefs: dict) -> str:
        s = ""
        for v, c in coefs.items():
            if c == 0:
                continue
            s += (f" + {c:g} {v}" if c >= 0 else f" - {abs(c):g} {v}")
        return s.strip() or "0"

    lines = ["Maximize", " obj:" + "".join(
        f" + {val[n]:.6f} {xn(n)}" for n in nodes if val[n]), "Subject To"]
    lines.append(f" root: {xn(root)} = 1")
    lines.append(" budget:" + "".join(f" + {cost[n]} {xn(n)}" for n in nodes if cost[n]) + f" <= {B}")

    arcs = [(a, b) for e in edges for (a, b) in (e, (e[1], e[0]))]
    out = {n: [] for n in nodes}
    inn = {n: [] for n in nodes}
    for a in arcs:
        out[a[0]].append(a)
        inn[a[1]].append(a)
    ci = 0
    for n in nodes:                                # connectivity: in - out = x (root sources all)
        coefs = {}
        for a in inn[n]:
            coefs[fn(*a)] = coefs.get(fn(*a), 0) + 1
        for a in out[n]:
            coefs[fn(*a)] = coefs.get(fn(*a), 0) - 1
        if n == root:
            for k in nodes:
                if k != root:
                    coefs[xn(k)] = coefs.get(xn(k), 0) + 1  # out - in = Σx  ->  in - out + Σx = 0
            lines.append(f" c{ci}: {expr(coefs)} = 0")
        else:
            coefs[xn(n)] = coefs.get(xn(n), 0) - 1
            lines.append(f" c{ci}: {expr(coefs)} = 0")
        ci += 1
    for a in arcs:                                 # capacity: f <= N·x  (both endpoints)
        lines.append(f" k{ci}: {fn(*a)} - {N} {xn(a[0])} <= 0"); ci += 1
        lines.append(f" k{ci}: {fn(*a)} - {N} {xn(a[1])} <= 0"); ci += 1
    lines.append("Binary")
    lines += [" " + xn(n) for n in nodes]
    lines.append("End")
    out_lp.write_text("\n".join(lines), encoding="utf-8")


def main():
    inst, _oracle, leader_id, member_ids = build_instance()
    add_socket_values(inst, leader_id, member_ids)
    board_json = {k: inst[k] for k in ("leader_id", "budget", "root", "nodes", "cost", "value")}
    board_json["edges"] = [list(e) for e in inst["edges"]]
    (HERE / "board.json").write_text(json.dumps(board_json), encoding="utf-8")
    write_lp(inst, HERE / "board.lp")
    reds = sum(1 for n in inst["nodes"] if n.startswith("R") and inst["value"][n] > 0)
    print(f"board.json + board.lp written: {len(inst['nodes'])} nodes, budget {inst['budget']}, "
          f"{reds} valued red, leader {leader_id}")


if __name__ == "__main__":
    main()
